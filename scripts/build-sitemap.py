#!/usr/bin/env python3
"""Rebuild sitemap.xml from what is actually on the site.

Run from the website repo root:

    python3 scripts/build-sitemap.py

Why this exists: the sitemap used to be hand-edited, so new guides got
appended and the original 22 were never added at all. Twenty-two of the
highest-traffic guides (heart-failure, copd, stroke, asthma...) were
invisible to search engines. Generating it from guides/catalog.json means
that cannot drift again — rebuild the catalog, then rebuild this.

Rules:
  * Guides come from guides/catalog.json, the single source of truth.
  * Free resource pages are listed: they are public, need no account, and
    are the main organic entry point.
  * Clean URLs (no .html), because that is what production serves; the
    .html forms only redirect to them.
  * Retired surfaces (Rounds, Community, Study sessions, AI tools) and the
    separate learn. subdomain are deliberately excluded. A sitemap may only
    contain URLs on its own host, so learn. never belonged here.
"""

import json
import pathlib
import datetime
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE = "https://thenursingcollective.pro"

# (path, changefreq, priority) — path "" is the homepage.
CORE_PAGES = [
    ("",              "weekly",  "1.0"),
    ("/pricing",      "monthly", "0.9"),
    ("/resources",    "weekly",  "0.9"),
    ("/my-guides",    "weekly",  "0.9"),
    ("/about",        "monthly", "0.6"),
    ("/contact",      "monthly", "0.6"),
    ("/login",        "monthly", "0.5"),
    ("/privacy",      "yearly",  "0.3"),
    ("/terms",        "yearly",  "0.3"),
]

# Pages that exist but are kept out of search deliberately.
EXCLUDED = {
    "rounds", "community", "study-session", "ai-tools", "checkout",
    "success", "settings", "dashboard", "admin", "admin-user", "status",
    "404", "auth-callback", "verify-email", "reset-password",
    "dashboard-nocache", "index", "about-florencebot",
}


def url_block(loc, lastmod, changefreq, priority):
    return (
        "    <url>\n"
        f"        <loc>{loc}</loc>\n"
        f"        <lastmod>{lastmod}</lastmod>\n"
        f"        <changefreq>{changefreq}</changefreq>\n"
        f"        <priority>{priority}</priority>\n"
        "    </url>\n"
    )


def main():
    today = datetime.date.today().isoformat()

    catalog_path = ROOT / "guides" / "catalog.json"
    if not catalog_path.exists():
        sys.exit("guides/catalog.json missing — run scripts/build-guide-catalog.py first")
    catalog = json.loads(catalog_path.read_text())
    guide_ids = sorted(catalog["guides"])

    # Only list guides whose page actually exists on disk.
    missing = [g for g in guide_ids if not (ROOT / "guides" / f"{g}.html").exists()]
    guide_ids = [g for g in guide_ids if g not in missing]

    resource_ids = sorted(
        p.stem for p in (ROOT / "resources").glob("*.html")
    )

    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
           '',
           f'    <!-- Generated by scripts/build-sitemap.py on {today}. Do not hand-edit. -->',
           '',
           '    <!-- Core pages -->']
    body = ""
    for path, freq, pri in CORE_PAGES:
        body += url_block(f"{BASE}{path}" if path else f"{BASE}/", today, freq, pri)
    out.append(body.rstrip("\n"))

    out.append("")
    out.append(f"    <!-- Free resource pages ({len(resource_ids)}) -->")
    body = ""
    for r in resource_ids:
        body += url_block(f"{BASE}/resources/{r}", today, "monthly", "0.8")
    out.append(body.rstrip("\n"))

    out.append("")
    out.append(f"    <!-- Study guides ({len(guide_ids)}) — from guides/catalog.json -->")
    body = ""
    for g in guide_ids:
        body += url_block(f"{BASE}/guides/{g}", today, "monthly", "0.7")
    out.append(body.rstrip("\n"))

    out.append("")
    out.append("</urlset>")

    (ROOT / "sitemap.xml").write_text("\n".join(out) + "\n")

    total = len(CORE_PAGES) + len(resource_ids) + len(guide_ids)
    print(f"sitemap.xml rebuilt: {total} URLs")
    print(f"  core pages      {len(CORE_PAGES)}")
    print(f"  free resources  {len(resource_ids)}")
    print(f"  study guides    {len(guide_ids)}")
    if missing:
        print(f"  WARNING: in catalog but no page on disk: {', '.join(missing)}")


if __name__ == "__main__":
    main()
